import { NextResponse } from "next/server";
import { getDb } from "@/lib/db";
import { getSession, type SessionUser } from "@/lib/session";
import {
  Q,
  parseFilters,
  suConditions,
  whereFrom,
  completeExpr,
  metricConditions,
  taskDone,
  type Filters,
} from "@/lib/analytics";
import { buildReport, type ReportPayload } from "@/lib/report";
import type { ConnectionPool } from "mssql";
import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";


function toISO(v: unknown): string {
  if (!v) return "";
  const d = new Date(v as string);
  return Number.isNaN(d.getTime()) ? "" : d.toISOString().slice(0, 10);
}

export async function GET(req: Request) {
  const user = await getSession();
  if (!user) return NextResponse.json({ message: "No session" }, { status: 401 });

  const sp = new URL(req.url).searchParams;
  const filters = parseFilters(sp);
  const report = sp.get("report") ?? "overview";
  const format = sp.get("format") === "pdf" ? "pdf" : "xlsx";

  if ((report === "beneficiaries" || report === "profile") && !user.details)
    return NextResponse.json(
      { message: "Your role cannot export detailed records." },
      { status: 403 },
    );

  try {
    const db = await getDb();
    let data: ReportPayload;
    if (report === "beneficiaries") {
      data = await beneficiariesData(db as ConnectionPool, {
        filters,
        user,
        metric: sp.get("metric") ?? "total",
        search: (sp.get("q") ?? "").trim(),
      });
    } else if (report === "profile") {
      data = await profileData(db as ConnectionPool, sp.get("id") ?? "", user);
    } else {
      data = await buildReport(db as ConnectionPool, {
        report,
        group: sp.get("group") ?? "project",
        measure: sp.get("metric") ?? "total",
        filters,
        user,
      });
    }

    const meta: [string, string][] = [
      ["Project", filters.project === "all" ? "All permitted projects" : filters.project],
      ["District", filters.district === "all" ? "All districts" : filters.district],
      ["Period", `${filters.start} to ${filters.end} (exclusive)`],
      ["Snapshot", data.asOf],
      ["Generated by", data.generatedBy],
    ];

    const filename = `sristi-${report}-report.${format}`;
    if (format === "xlsx") {
      const buf = await renderXlsx(data, meta);
      return new NextResponse(new Uint8Array(buf), {
        headers: {
          "Content-Type":
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
          "Content-Disposition": `attachment; filename="${filename}"`,
        },
      });
    }
    const buf = await renderPdf(data, meta);
    return new NextResponse(new Uint8Array(buf), {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="${filename}"`,
      },
    });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : String(err);
    return NextResponse.json({ message }, { status: 500 });
  }
}

async function beneficiariesData(
  db: ConnectionPool,
  opts: { filters: Filters; user: SessionUser; metric: string; search: string },
): Promise<ReportPayload> {
  const { filters, user, metric, search } = opts;
  const q = new Q(db);
  const conds = suConditions(q, filters, user);
  conds.push(
    ...metricConditions(metric, q.p(new Date(filters.start)), q.p(new Date(filters.end))),
  );
  if (search) {
    const like = q.p("%" + search + "%");
    conds.push(`(sm.su_name LIKE ${like} OR sm.su_patientno LIKE ${like})`);
  }
  const res = await q.query<Record<string, unknown>>(`
    SELECT TOP 5000 sm.su_patientno, sm.su_name, sm.su_program, sm.su_district,
           COALESCE(u.usr_name, sm.su_owner) AS su_owner,
           CASE WHEN sm.su_isActive = 1 AND (sm.su_discharged = 0 OR sm.su_discharged IS NULL) THEN 'Active' ELSE 'Inactive' END AS status,
           CASE WHEN ${completeExpr()} = 1 THEN 'Complete' ELSE 'Incomplete' END AS completeness,
           (SELECT MAX(t.task_date) FROM task_mstr t WHERE t.task_serviceuser = sm.su_id AND ${taskDone("t.")}) AS last_service
    FROM serviceuser_mstr sm
    LEFT JOIN User_mstr u ON u.usr_id = sm.su_owner
    ${whereFrom(conds)} ORDER BY sm.su_name`);
  return {
    title: "Beneficiary register",
    headers: ["ID", "Name", "Program", "District", "Worker", "Last service", "Status", "Record"],
    rows: res.recordset.map((r) => [
      String(r.su_patientno ?? ""),
      String(r.su_name ?? ""),
      String(r.su_program ?? ""),
      String(r.su_district ?? ""),
      String(r.su_owner ?? ""),
      toISO(r.last_service),
      String(r.status),
      String(r.completeness),
    ]),
    asOf: new Date().toISOString().slice(0, 10),
    generatedBy: `${user.name} (${user.label})`,
  };
}

async function profileData(
  db: ConnectionPool,
  id: string,
  user: SessionUser,
): Promise<ReportPayload> {
  const q = new Q(db);
  const res = await q.query<Record<string, unknown>>(`
    SELECT su_id, su_patientno, su_name, su_sex, su_program, su_district, su_owner,
           su_age, su_isActive, su_discharged, su_dateofadmission
    FROM serviceuser_mstr WHERE su_id = ${q.p(id)}`);
  const row = res.recordset[0];
  if (!row) throw new Error("Profile not found.");
  if (
    user.program &&
    String(row.su_program ?? "").toLowerCase() !== user.program.toLowerCase()
  )
    throw new Error("Outside your scope.");
  const rows: (string | number | null)[][] = [
    ["Beneficiary ID", String(row.su_patientno ?? row.su_id)],
    ["Name", String(row.su_name ?? "")],
    ["Program", String(row.su_program ?? "")],
    ["District", String(row.su_district ?? "")],
    ["Assigned worker", String(row.su_owner ?? "")],
    ["Age", String(row.su_age ?? "")],
    ["Registered", toISO(row.su_dateofadmission)],
    [
      "Status",
      Number(row.su_isActive) === 1 && Number(row.su_discharged) !== 1
        ? "Active"
        : "Inactive",
    ],
  ];
  return {
    title: "Beneficiary profile summary",
    headers: ["Field", "Value"],
    rows,
    asOf: new Date().toISOString().slice(0, 10),
    generatedBy: `${user.name} (${user.label})`,
  };
}

async function renderXlsx(
  data: ReportPayload,
  meta: [string, string][],
): Promise<ArrayBuffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "Sristi Foundation Dashboard";
  const ws = wb.addWorksheet("Report");
  const titleRow = ws.addRow([data.title]);
  titleRow.font = { bold: true, size: 14 };
  ws.addRow([]);
  meta.forEach(([k, v]) => {
    const r = ws.addRow([k, v]);
    r.getCell(1).font = { bold: true };
  });
  ws.addRow([]);
  const head = ws.addRow(data.headers);
  head.font = { bold: true };
  head.eachCell((c) => {
    c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE6E9DF" } };
  });
  data.rows.forEach((row) =>
    ws.addRow(row.map((v) => (v === null ? "Suppressed" : v))),
  );
  data.headers.forEach((h, i) => {
    const col = ws.getColumn(i + 1);
    const maxLen = Math.max(
      h.length,
      ...data.rows.map((r) => String(r[i] ?? "").length),
    );
    col.width = Math.min(48, Math.max(12, maxLen + 2));
  });
  return wb.xlsx.writeBuffer() as Promise<ArrayBuffer>;
}

function renderPdf(
  data: ReportPayload,
  meta: [string, string][],
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 40, size: "A4" });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(18).fillColor("#244b3e").text("Sristi Foundation", { continued: false });
    doc.fontSize(13).fillColor("#333").text(data.title);
    doc.moveDown(0.5);
    doc.fontSize(9).fillColor("#666");
    meta.forEach(([k, v]) => doc.text(`${k}: ${v}`));
    doc.moveDown(0.6);

    const left = doc.page.margins.left;
    const usable = doc.page.width - left - doc.page.margins.right;
    const cols = data.headers.length;
    const colW = usable / cols;
    const rowH = 16;

    const drawRow = (cells: (string | number | null)[], bold: boolean) => {
      if (doc.y + rowH > doc.page.height - doc.page.margins.bottom) doc.addPage();
      const y = doc.y;
      doc.fontSize(8).fillColor(bold ? "#111" : "#333").font(bold ? "Helvetica-Bold" : "Helvetica");
      cells.forEach((c, i) => {
        const text = c === null ? "Suppressed" : String(c);
        doc.text(text, left + i * colW + 2, y + 4, {
          width: colW - 4,
          height: rowH,
          ellipsis: true,
          lineBreak: false,
        });
      });
      doc.rect(left, y, usable, rowH).strokeColor("#e6e9df").lineWidth(0.5).stroke();
      doc.y = y + rowH;
    };

    drawRow(data.headers, true);
    data.rows.forEach((r) => drawRow(r, false));

    doc.moveDown(1);
    doc
      .fontSize(8)
      .fillColor("#888")
      .font("Helvetica")
      .text(
        `${data.rows.length} rows · read-only reporting · generated ${data.asOf}`,
      );
    doc.end();
  });
}
